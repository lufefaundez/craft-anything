#!/usr/bin/env python3
"""Generates Fluent Light/Dark design tokens for Android Jetpack Compose (.kt) and Apple SwiftUI (.swift)."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

SUITE_DIR = Path(__file__).resolve().parent.parent
TOKENS_PATH = SUITE_DIR / "specs" / "fluent-tokens.json"
KT_OUT = SUITE_DIR / "docxdocx/apps/android/app/src/main/java/app/ofiofi/docxdocx/ui/theme/OfficeTokens.kt"
SWIFT_OUT = SUITE_DIR / "docxdocx/apps/apple/Packages/OfficeCoreKit/Sources/OfficeCoreKit/Theme/OfficeTokens.swift"


def parse_hex_rgba(value: str) -> tuple[int, int, int, int]:
    raw = value.strip().lstrip("#")
    if len(raw) == 6:
        r, g, b = int(raw[0:2], 16), int(raw[2:4], 16), int(raw[4:6], 16)
        return (r, g, b, 0xFF)
    if len(raw) == 8:
        # #RRGGBBAA -> (R, G, B, A)
        r, g, b, a = int(raw[0:2], 16), int(raw[2:4], 16), int(raw[4:6], 16), int(raw[6:8], 16)
        return (r, g, b, a)
    raise ValueError(f"Unsupported hex color format: {value}")


def to_camel(name: str) -> str:
    parts = name.split("_")
    return parts[0] + "".join(p.capitalize() for p in parts[1:])


def to_pascal(name: str) -> str:
    return "".join(p.capitalize() for p in name.split("_"))


def kt_color(hex_str: str) -> str:
    r, g, b, a = parse_hex_rgba(hex_str)
    argb = (a << 24) | (r << 16) | (g << 8) | b
    return f"Color(0x{argb:08X})"


def swift_color(hex_str: str) -> str:
    r, g, b, a = parse_hex_rgba(hex_str)
    return (
        f"Color(.sRGB, red: {r / 255.0:.4f}, green: {g / 255.0:.4f}, "
        f"blue: {b / 255.0:.4f}, opacity: {a / 255.0:.4f})"
    )


def render_kotlin(data: dict) -> str:
    lines = [
        "// GENERATED BY office-suite/scripts/gen_tokens.py from specs/fluent-tokens.json — DO NOT EDIT.",
        "package app.ofiofi.docxdocx.ui.theme",
        "",
        "import androidx.compose.ui.graphics.Color",
        "import androidx.compose.ui.unit.Dp",
        "import androidx.compose.ui.unit.dp",
        "",
        "object OfficeTokens {",
        f'    const val VERSION: String = "{data["version"]}"',
        "",
        "    object Radii {",
    ]
    for k, v in data["radii_dp"].items():
        lines.append(f"        val {to_camel(k)}: Dp = {v}.dp")
    lines += ["    }", "", "    object TouchTargets {"]
    for k, v in data["touch_targets_dp"].items():
        lines.append(f"        val {to_camel(k)}: Dp = {v}.dp")
    lines += ["    }", "", "    object AppAccents {"]
    for app_name, props in data["apps"].items():
        lines.append(f"        object {to_pascal(app_name)} {{")
        for k, v in props.items():
            lines.append(f"            val {to_camel(k)}: Color = {kt_color(v)}")
        lines.append("        }")
    lines += ["    }", "", "    data class SurfacePalette("]
    light_keys = list(data["surfaces"]["light"].keys())
    for k in light_keys:
        lines.append(f"        val {to_camel(k)}: Color,")
    lines += [
        "        val pageDarkMode: Color,",
        "    )",
        "",
        "    val LightSurfaces = SurfacePalette(",
    ]
    for k, v in data["surfaces"]["light"].items():
        lines.append(f"        {to_camel(k)} = {kt_color(v)},")
    lines += [
        f'        pageDarkMode = {kt_color(data["surfaces"]["dark"]["page_dark_mode"])},',
        "    )",
        "",
        "    val DarkSurfaces = SurfacePalette(",
    ]
    for k in light_keys:
        lines.append(f'        {to_camel(k)} = {kt_color(data["surfaces"]["dark"][k])},')
    lines += [
        f'        pageDarkMode = {kt_color(data["surfaces"]["dark"]["page_dark_mode"])},',
        "    )",
        "}",
        "",
    ]
    return "\n".join(lines)


def render_swift(data: dict) -> str:
    lines = [
        "// GENERATED BY office-suite/scripts/gen_tokens.py from specs/fluent-tokens.json — DO NOT EDIT.",
        "import SwiftUI",
        "",
        "public enum OfficeTokens {",
        f'    public static let version: String = "{data["version"]}"',
        "",
        "    public enum Radii {",
    ]
    for k, v in data["radii_dp"].items():
        lines.append(f"        public static let {to_camel(k)}: CGFloat = {v}")
    lines += ["    }", "", "    public enum TouchTargets {"]
    for k, v in data["touch_targets_dp"].items():
        lines.append(f"        public static let {to_camel(k)}: CGFloat = {v}")
    lines += ["    }", "", "    public enum AppAccents {"]
    for app_name, props in data["apps"].items():
        lines.append(f"        public enum {to_pascal(app_name)} {{")
        for k, v in props.items():
            lines.append(f"            public static let {to_camel(k)} = {swift_color(v)}")
        lines.append("        }")
    lines += ["    }", "", "    public struct SurfacePalette: Sendable {"]
    light_keys = list(data["surfaces"]["light"].keys())
    for k in light_keys:
        lines.append(f"        public let {to_camel(k)}: Color")
    lines += [
        "        public let pageDarkMode: Color",
        "    }",
        "",
        "    public static let lightSurfaces = SurfacePalette(",
    ]
    for k, v in data["surfaces"]["light"].items():
        lines.append(f"        {to_camel(k)}: {swift_color(v)},")
    lines += [
        f'        pageDarkMode: {swift_color(data["surfaces"]["dark"]["page_dark_mode"])}',
        "    )",
        "",
        "    public static let darkSurfaces = SurfacePalette(",
    ]
    for k in light_keys:
        lines.append(f'        {to_camel(k)}: {swift_color(data["surfaces"]["dark"][k])},')
    lines += [
        f'        pageDarkMode: {swift_color(data["surfaces"]["dark"]["page_dark_mode"])}',
        "    )",
        "}",
        "",
    ]
    return "\n".join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description="Generate OfficeTokens.kt and OfficeTokens.swift")
    parser.add_argument("--check", action="store_true", help="Verify generated files match specs/fluent-tokens.json")
    args = parser.parse_args()

    data = json.loads(TOKENS_PATH.read_text(encoding="utf-8"))
    outputs = {
        KT_OUT: render_kotlin(data),
        SWIFT_OUT: render_swift(data),
    }

    if args.check:
        stale = []
        for path, expected in outputs.items():
            if not path.is_file() or path.read_text(encoding="utf-8") != expected:
                stale.append(str(path.relative_to(SUITE_DIR)))
        if stale:
            print(f"ERROR: Token files out of date or missing: {stale}", file=sys.stderr)
            return 1
        print("gen_tokens --check OK: OfficeTokens.kt and OfficeTokens.swift match specs/fluent-tokens.json")
        return 0

    for path, content in outputs.items():
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        print(f"Wrote {path.relative_to(SUITE_DIR)} ({len(content)} bytes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
